def layer_of_integration(abc_grid,kabc,ilayer,zlayer,Lpbc):
    """
    This function is highly case-specific. It returns the grid indices for which
    the space integration is to perform. Very likely, the user will need to modify
    this function very often. ilayer = 1 to 6, corresponding to index 0 to 5.
    The boolean Lpbc input indicates whether the periodic boundary condition along
    The z axis applies.
    """

   #safety check
    if abs(abc_grid[0,2])*abs(abc_grid[1,2]) > 1.0e-4:
        print(f'\n!!! a and b vectors contain nonzero z component. Bombing out!')
        sys.exit()

   #print('ilayer=',ilayer)
   #Adjust ilayer to index
    ilayer -= 1
   #hand put in
   #zlayer = [4.757299,14.2714225,23.785546,33.300144,42.8142675,52.328391]
    nlayer = len(zlayer)

    if ilayer != nlayer - 1 and ilayer != 0:
        zlow = 0.5 * (zlayer[ilayer] + zlayer[ilayer - 1])
        zup  = 0.5 * (zlayer[ilayer] + zlayer[ilayer + 1])
    if ilayer == 0:
        zup  = 0.5 * (zlayer[ilayer] + zlayer[ilayer + 1])
        if Lpbc:
            zlow = 0.5 * (zlayer[ilayer] + zlayer[nlayer-1] - abc_grid[2,2]*kabc[2])
        else:
            zlow = zlayer[ilayer] - (zup - zlayer[ilayer])
    if ilayer == nlayer-1:
        zlow = 0.5 * (zlayer[ilayer] + zlayer[ilayer - 1])
        if Lpbc:
            zup  = 0.5 * (zlayer[ilayer] + zlayer[0] + abc_grid[2,2]*kabc[2])
        else:
            zup  = zlayer[ilayer] + (zlayer[ilayer] - zlow)

   #print(zlow,zup)

    iclow = int(zlow / abc_grid[2,2])
    icup = int(zup / abc_grid[2,2])


    list_points_intgrl = []
    for ic in range(iclow,icup):
        ictrue = ic
        if ic >= kabc[2]: ictrue = ic - kabc[2]
        if ic < 0: ictrue = ic + kabc[2]
        for ia in range(kabc[0]):
           for ib in range(kabc[1]): 
               list_points_intgrl.append([ia,ib,ictrue])
   #for ia in range(kabc[0]):
   #    for ib in range(kabc[1]):
   #        for ic in range(kabc[2]):
   #           rvec=ia*abc_grid[0,:]+ib*abc_grid[1,:]+ic*abc_grid[2,:]
            

   #print(len(list_points_intgrl))
    print(list_points_intgrl[0],list_points_intgrl[0][2]*abc_grid[2,2])
    print(list_points_intgrl[-1],list_points_intgrl[-1][2]*abc_grid[2,2])

    npoints = len(list_points_intgrl)
    print(f'\nPoints to be integrated: {npoints}')

    return list_points_intgrl

def localize_orbitals(orb_list,orb_cube_list,list_points):
    """
    Read in a list of orbitals, and a list of point indices
    return orbitals localized on the spatial region of the points
    """

    debug = False

   #print(orb_list)
    print(list_points[0])
    print(list_points[-1])

    norb = len(orb_list)
   #print(norb)

    Smat = np.zeros([norb,norb])

    for i in range(norb):
        iorb = orb_list[i]
        iorb_cube = orb_cube_list[i]
        for j in range(i,norb):
            jorb = orb_list[j]
            jorb_cube = orb_cube_list[j]
            print(iorb,jorb)
            dsum = 0.0
            for ipoint in range(len(list_points)):
                ia, ib, ic = list_points[ipoint][0], list_points[ipoint][1],list_points[ipoint][2]
                dsum += iorb_cube[ia,ib,ic] * jorb_cube[ia,ib,ic]

            Smat[i,j] = dsum
            Smat[j,i] = dsum

    print(f'\nRegional overlap matrix of the orbitals:')
    for row in Smat:
        print(" ".join(f"{num:12.6f}" for num in row))

    Smat = np.array(Smat)
    S_eigval, S_eigvec = np.linalg.eig(Smat)

    print(f'\nEigenvalues of the regional overlap matrix:')
    print(" ".join(f"{num:12.6f}" for num in S_eigval))
    print(f'\nEigenvectors of the regional overlap matrix:')
    for row in S_eigvec:
        print(" ".join(f"{num:12.6f}" for num in row))

    na, nb, nc = [jorb_cube.shape[i] for i in (0, 1, 2)]

    threshold = 0.4
    n_locorb = 0
    locorb_cube = []
    for locorb in range(norb):
        if S_eigval[locorb] > threshold:
            n_locorb += 1
            print(f'Eigvec {locorb} recorded')
            orbsum = np.zeros([na,nb,nc])
            for icmo in range(norb):
                orbsum += orb_cube_list[icmo] * S_eigvec[icmo,locorb]
           #    print(S_eigvec[icmo,locorb])

