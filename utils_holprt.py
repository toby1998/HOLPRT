    for hole_canon_orb in hole_canon_list:
        natoms,crdorg,kabc,abc_grid,iatsrl,crdatm,hole_cube = read_cube_file(str(hole_canon_orb)+'.cube',True)
        hole_canon_cube_list.append(hole_cube)

    print(f'Now reading canonical particle cube files')
    for part_canon_orb in part_canon_list:
        natoms,crdorg,kabc,abc_grid,iatsrl,crdatm,part_cube = read_cube_file(str(part_canon_orb)+'.cube',True)
