def get_b_from_a(a_vec):
    """
    Get the b vectors from a vectors for a cell
    The returned b is in unit of radian / length. There is no need to multiply 2pi.
    """
    denorm = np.dot(a_vec[0],np.cross(a_vec[1],a_vec[2]))
   #print(denorm)

    b_vec = np.zeros([3,3])

    b_vec[0,:] = 2.0*np.pi*np.cross(a_vec[1],a_vec[2])/denorm
    b_vec[1,:] = 2.0*np.pi*np.cross(a_vec[2],a_vec[0])/denorm
    b_vec[2,:] = 2.0*np.pi*np.cross(a_vec[0],a_vec[1])/denorm

   #print(b_vec)

    for i in range(3):
        for j in range(3):
           #print(i,j,np.dot(b_vec[i,:],a_vec[j,:]))
            if i != j:
                assert abs(np.dot(b_vec[i,:],a_vec[j,:])) < 1.0e-8
            else:
                assert abs(np.dot(b_vec[i,:],a_vec[j,:])-2.0*np.pi) < 1.0e-8

    return b_vec

def get_k_component(kcell,abc_grid,abc_vec,b_vec,kmesh,ncell,cube_unitcell,cube_grid):
    """
    Get phases of k dot r for all grids in a cube file
    """
    kvec = np.zeros([3])
    for idim in range(3):
        kvec += float(kmesh[idim])/float(ncell[idim])*b_vec[idim,:]

    phase_angle_grid = np.zeros([kcell[0],kcell[1],kcell[2]])
    sin_grid_1stcell = np.zeros([kcell[0],kcell[1],kcell[2]])
    cos_grid_1stcell = np.zeros([kcell[0],kcell[1],kcell[2]])
    sin_grid_cell = np.zeros([kcell[0]*ncell[0],kcell[1]*ncell[1],kcell[2]*ncell[2]])
    cos_grid_cell = np.zeros([kcell[0]*ncell[0],kcell[1]*ncell[1],kcell[2]*ncell[2]])
   #print(kvec)
    for ia in range(kcell[0]):
        rvec1 = abc_grid[0,:]*ia
        for ib in range(kcell[1]):
            rvec2 = rvec1 + abc_grid[1,:]*ib
           #print(ia,ib)
            for ic in range(kcell[2]):
                rvec = rvec2 + abc_grid[2,:]*ic
                phase_angle_grid[ia,ib,ic] = np.dot(rvec,kvec)
                            
    sin_grid_1stcell = np.sin(phase_angle_grid)
    cos_grid_1stcell = np.cos(phase_angle_grid)

    sin_sum = 0.0
    cos_sum = 0.0
    for iacell in range(ncell[0]):
        rvec1 = abc_vec[0,:]*iacell
        for ibcell in range(ncell[1]):
            rvec2 = rvec1 + abc_vec[1,:]*ibcell
            for iccell in range(ncell[2]):
                rvec = rvec2 + abc_vec[2,:]*iccell
                phase_angle = np.dot(rvec,kvec)
                sin_grid_cell = sin_grid_1stcell * np.cos(phase_angle) + cos_grid_1stcell * np.sin(phase_angle)
                cos_grid_cell = cos_grid_1stcell * np.cos(phase_angle) - sin_grid_1stcell * np.sin(phase_angle)
                cube_grid_cell = cube_grid[iacell*kcell[0]:(iacell+1)*kcell[0],\
                                           ibcell*kcell[1]:(ibcell+1)*kcell[1],\
                                           iccell*kcell[2]:(iccell+1)*kcell[2]]
                sin_sum += np.sum(sin_grid_cell * cube_unitcell * cube_grid_cell)
                cos_sum += np.sum(cos_grid_cell * cube_unitcell * cube_grid_cell)

   #if abs(sin_sum) + abs(cos_sum) > 0.1: print(sin_sum,cos_sum)
    return sin_sum,cos_sum

def find_cell_max_ampld_in_supercell(cube_grid,ncell,kcell):
    """
    In the cube grid of a supercell, find the unit cell with the maximum amplitude and return
    the cube data of that unit cell
    """
    cell_sum_max = 0.0
    for iacell in range(ncell[0]):
        for ibcell in range(ncell[1]):
            for iccell in range(ncell[2]):
                cell_sum = np.sum(\
                cube_grid[iacell*kcell[0]:(iacell+1)*kcell[0],\
                          ibcell*kcell[1]:(ibcell+1)*kcell[1],\
                          iccell*kcell[2]:(iccell+1)*kcell[2]]*\
                cube_grid[iacell*kcell[0]:(iacell+1)*kcell[0],\
                          ibcell*kcell[1]:(ibcell+1)*kcell[1],\
                          iccell*kcell[2]:(iccell+1)*kcell[2]])
               #print(iacell,ibcell,iccell,cell_sum)
                if cell_sum > cell_sum_max:
                    cell_sum_max = cell_sum
                    ia_cell_max = iacell
                    ib_cell_max = ibcell
                    ic_cell_max = iccell

   #print(f'max norm {np.around(cell_sum_max,4)} at cell index: {ia_cell_max,ib_cell_max,ic_cell_max}')
    cube_max_unitcell = cube_grid[ia_cell_max*kcell[0]:(ia_cell_max+1)*kcell[0],\
                              ib_cell_max*kcell[1]:(ib_cell_max+1)*kcell[1],\
                              ic_cell_max*kcell[2]:(ic_cell_max+1)*kcell[2]].copy()

    return cube_max_unitcell

