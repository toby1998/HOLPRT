def symmetric_orthogonalization(S, eps=1e-10):
    S = 0.5 * (S + S.conj().T)
    w, X = np.linalg.eigh(S)
    if not np.all(np.isfinite(w)):
        raise ValueError("Overlap eigenvalues contain NaN/Inf.")
    wmax = np.max(np.abs(w)) if w.size else 0.0
    thresh = eps * max(1.0, wmax)
    w_clipped = np.clip(w, thresh, None)
    inv_sqrt = 1.0 / np.sqrt(w_clipped)
    O = (X * inv_sqrt) @ X.conj().T
    return O

def purify_k_orbitals(list_input_cube_files,ncell,kmesh,output_filename):
    """
    Purify the k vector for orbitals
    kmesh / ncell gives the k grids. E.g., kmesh = [2,2,0] and ncell = [4,4,1] gives k = [1/2, 1/2, 0]
    """

    norb_input = len(list_input_cube_files)
    input_cube_list = []
    for input_orb in list_input_cube_files:
        natoms,crdorg,kabc,abc_grid,iatsrl,crdatm,cube_grid = read_cube_file(input_orb,True)
        input_cube_list.append(cube_grid)

    kcell = kabc // ncell
    print(kcell)

    unitcell_cube = np.zeros([kcell[0],kcell[1],kcell[2]])
    for i in range(norb_input):
        unitcell_cube += find_cell_max_ampld_in_supercell(input_cube_list[i],ncell,kcell)

    dnorm = np.sqrt(np.sum(unitcell_cube**2.0)*ncell[0]*ncell[1]*ncell[2])

    unitcell_cube /= dnorm

    abc_vec = np.zeros([3,3])
    for i in range(3):
        abc_vec[i,:] = abc_grid[i,:] * kcell[i]

   #print(abc_vec)
    b_vec = get_b_from_a(abc_vec)

    S_korb_orbinput_cos = np.zeros([norb_input])
    S_korb_orbinput_sin = np.zeros([norb_input])
    for i in range(norb_input):
        kh_sin,kh_cos = get_k_component(kcell,abc_grid,abc_vec,b_vec,kmesh,ncell,unitcell_cube,input_cube_list[i])
        S_korb_orbinput_cos[i] = kh_cos
        S_korb_orbinput_sin[i] = kh_sin

    S_kproj = np.zeros([norb_input,norb_input])
    for i in range(norb_input):
        for j in range(i,norb_input):
            S_kproj[i,j] = S_korb_orbinput_cos[i]*S_korb_orbinput_cos[j] +\
                           S_korb_orbinput_sin[i]*S_korb_orbinput_sin[j]
            S_kproj[j,i] = S_kproj[i,j]

    print(S_kproj)
    S_kproj_eigval,  S_kproj_eigvec = np.linalg.eigh(S_kproj)

    print(" ".join(f"{num:12.6f}" for num in S_kproj_eigval))
    print("")
    for row in S_kproj_eigvec:
        print(" ".join(f"{num:12.6f}" for num in row))

    cube_output = input_cube_list[0].copy() * S_kproj_eigvec[0,-1]
    for i in range(1,norb_input):
        cube_output += S_kproj_eigvec[i,-1] * input_cube_list[i]

   #filnam = 'K_adapted.cube' 
    Line2_text = 'No contents are given' + '\n'
    write_cube_file(output_filename,natoms,crdorg,kabc,abc_grid,iatsrl,crdatm,cube_output,Line2_text)

