def build_k_adapted_mode(mode_periodic,kmesh,cos_or_sin,abc_vec,b_vec,ncells,atom_cell_ind):
   #print(f'in build_k_adapted_mode')

    kvec = np.zeros([3])
    for idim in range(3):
        kvec += float(kmesh[idim])/float(ncells[idim])*b_vec[idim,:]

    mode_k_adapted = mode_periodic.copy()
    icell = 0
    for iacell in range(ncells[0]):
        rvec1 = abc_vec[0,:]*iacell
        for ibcell in range(ncells[1]):
            rvec2 = rvec1 + abc_vec[1,:]*ibcell
            for iccell in range(ncells[2]):
                rvec = rvec2 + abc_vec[2,:]*iccell
                phase_angle = np.dot(rvec,kvec)
                for iatom in atom_cell_ind[icell]:
                    if cos_or_sin == 'cos':
                        mode_k_adapted[3*iatom:3*iatom+3] *= np.cos(phase_angle)
                    elif cos_or_sin == 'sin':
                        mode_k_adapted[3*iatom:3*iatom+3] *= np.sin(phase_angle)
                    else:
                        print(f'Unrecognized cos_or_sin: {cos_or_sin}. Bombing out!')
                        sys.exit()

                icell += 1

    dnorm = np.linalg.norm(mode_k_adapted)
    if dnorm > 1.0e-5: mode_k_adapted /= dnorm

    return mode_k_adapted

