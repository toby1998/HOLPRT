def orthonormalize_trimmed_adiabats(ihole,ipart,cicoef,list_states_of_interest):
    print(f'in orthonormalize_trimmed_adiabats')

    list_unique_hp_pair = []
   #First find the unique hole-particle pair as the basis 
    for state in list_states_of_interest:
        istate = state - 1
        for ihp in range(len(cicoef[istate])):
            hole = ihole[istate][ihp]
            part = ipart[istate][ihp]
            if [hole,part] not in list_unique_hp_pair:
                list_unique_hp_pair.append([hole,part])

    print(f'Unique hole-part pairs in states of interest:')
    print(list_unique_hp_pair)
    n_hp_pair = len(list_unique_hp_pair)
    n_states_of_interest = len(list_states_of_interest)
    adiabats_trim = np.zeros([n_hp_pair,n_states_of_interest])
    iadiab = -1
    for state in list_states_of_interest:
        istate = state - 1
        iadiab += 1
        for ihp in range(len(cicoef[istate])):
            hole = ihole[istate][ihp]
            part = ipart[istate][ihp]
            ibasis = list_unique_hp_pair.index([hole,part])
            adiabats_trim[ibasis,iadiab] = cicoef[istate][ihp]

    print(f'\nTrimmed adiabats in hp pair basis')
    print_matrix(adiabats_trim)

    S=adiabats_trim.transpose()@adiabats_trim
    print(f'\nOverlap matrix between trimmed adiabats')
    print_matrix(S)

    sym_ortho = symmetric_orthogonalization(S)
    print(f'Symmetric orthogonalization matrix')
    print_matrix(sym_ortho)

    adiabats_orthonormal = adiabats_trim@sym_ortho

    assert np.allclose(adiabats_orthonormal.transpose()@adiabats_orthonormal,np.identity(n_states_of_interest))

    iadiab = -1
    for state in list_states_of_interest:
        istate = state - 1
        iadiab += 1
        for ihp in range(len(cicoef[istate])):
            hole = ihole[istate][ihp]
            part = ipart[istate][ihp]
            ibasis = list_unique_hp_pair.index([hole,part])
            cicoef[istate][ihp] = adiabats_orthonormal[ibasis,iadiab]

        print(f'State {state} after triming and re-orthonormalization:')
        print(ihole[istate])
        print(ipart[istate])
        print(cicoef[istate])

