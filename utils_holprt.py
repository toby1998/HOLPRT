def holprt_proj_trnden(hpcubefile,sglval,orbhol_nat,orbprt_nat,holorprt,filnam):
    """
    Project a hole or a particle orbital onto a transition density to 
    get the associated particle or hole orbital
    """

    debug = True

    if holorprt != 'HOLPRJ2PRT' and holorprt != 'PRTPRJ2HOL':
        print(f'\n!!!holorprt can only be HOLPRJ2PRT or PRTPRJ2HOL. Bombing out')
        print(holorprt)
        sys.exit()

    file_exists(hpcubefile)

    Lnorm = True
