def orb_proj(list_input_cube_files,ncell):
    """
    Given a set of orbitals, using the last one as the reference, rotating the rest to have
    the maximum overlap with the reference. This is useful to symmetrize some degenerate orbitals
    """

    norb_input = len(list_input_cube_files)
    norb_rotated = norb_input - 1
    input_cube_list = []
    for input_orb in list_input_cube_files:
        natoms,crdorg,kabc,abc_grid,iatsrl,crdatm,cube_grid = read_cube_file(input_orb,True)
        input_cube_list.append(cube_grid)

    kcell = kabc // ncell

    abc_vec = np.zeros([3,3])
    for i in range(3):
        abc_vec[i,:] = abc_grid[i,:] * kcell[i]

   #print(abc_vec)
    b_vec = get_b_from_a(abc_vec)

    refcube = input_cube_list[-1]
    unitcell_refcube = find_cell_max_ampld_in_supercell(refcube,ncell,kcell)

    dnorm = np.sqrt(np.sum(unitcell_refcube**2.0)*ncell[0]*ncell[1]*ncell[2])

    unitcell_refcube /= dnorm

    kmesh = np.array([0,0,0])

    S_with_ref = np.zeros([norb_rotated])
    S_proj = np.zeros([norb_rotated,norb_rotated])
    for i in range(norb_rotated):
        kh_sin,kh_cos = get_k_component(kcell,abc_grid,abc_vec,b_vec,kmesh,ncell,unitcell_refcube,input_cube_list[i])
       #kh_sin must be zero with the 0 0 0 kmesh and discarded.
        S_with_ref[i] = kh_cos

    for i in range(norb_rotated):
        for j in range(i,norb_rotated):
            S_proj[i,j] = S_with_ref[i]*S_with_ref[j]
            S_proj[j,i] = S_proj[i,j]

    S_proj_eigval,  S_proj_eigvec = np.linalg.eigh(S_proj)

    print_eigen_solution(S_proj_eigval,S_proj_eigvec)

    for ieig in range(norb_rotated):
        eigcube = input_cube_list[0]*S_proj_eigvec[0,ieig]
        for iorb in range(1,norb_rotated):
            eigcube += input_cube_list[iorb]*S_proj_eigvec[iorb,ieig]

        Line2_text = 'No contents are given' + '\n'
        filnam = 'Projected_Orb' + str(ieig) + '.cube'
        write_cube_file(filnam,natoms,crdorg,kabc,abc_grid,iatsrl,crdatm,eigcube,Line2_text)

