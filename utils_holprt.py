def proj_orbs(list_orb_to_proj,list_orb_proj_to,n_collect,cube_orb_to_proj=[],cube_orb_proj_to=[],lwrite=False):
    """
    Project the orbitals in list_orb_to_proj to the space of orbitals in list_orb_proj_to
    and collect the n_collect resultant orbitals with the largest projections
    """
   #print(f'in proj_orbs')
   #cube_orb_to_proj = []
    if len(cube_orb_to_proj) == 0:
        for i,cubefile in enumerate(list_orb_to_proj):
            file_exists(cubefile)
            print(f'Reading cube file {cubefile}')
    
            Lnorm = True
            natoms,crdorg,kabc,abc_grid,iatsrl,crdatm,cubedata = read_cube_file(cubefile,Lnorm)
            cube_orb_to_proj.append(cubedata)

   #cube_orb_proj_to = []
    if len(cube_orb_proj_to) == 0:
        for i,cubefile in enumerate(list_orb_proj_to):
            file_exists(cubefile)
            print(f'Reading cube file {cubefile}')
    
            Lnorm = True
            natoms,crdorg,kabc,abc_grid,iatsrl,crdatm,cubedata = read_cube_file(cubefile,Lnorm)
            cube_orb_proj_to.append(cubedata)

    assert len(list_orb_to_proj) == len(cube_orb_to_proj)
    assert len(list_orb_proj_to) == len(cube_orb_proj_to)

    n_to_proj = len(list_orb_to_proj)
    n_proj_to = len(list_orb_proj_to)
    S_to_proj_proj_to = np.zeros([n_to_proj,n_proj_to])
    for i_to_proj in range(n_to_proj):
        for j_proj_to in range(n_proj_to):
            S_to_proj_proj_to[i_to_proj,j_proj_to] = np.sum(cube_orb_to_proj[i_to_proj]*cube_orb_proj_to[j_proj_to])

   #print(S_to_proj_proj_to)

    proj_mat = np.zeros([n_to_proj,n_to_proj])
    for i in range(n_to_proj):
        for j in range(i,n_to_proj):
           #print(i,j)
            proj_mat[i,j] = np.sum(S_to_proj_proj_to[i,:]*S_to_proj_proj_to[j,:])
            proj_mat[j,i] = proj_mat[i,j]

   #print(proj_mat)
    proj_mat_eigval, proj_mat_eigvec = np.linalg.eigh(proj_mat)
   #Adjust phase to have positive overlap when there is only one orbital to project to
    phase = np.sum(proj_mat_eigvec[:,-1]*S_to_proj_proj_to[:,0])
    if phase < 0.0: proj_mat_eigvec[:,-1] = -proj_mat_eigvec[:,-1]
    print_eigen_solution(proj_mat_eigval,proj_mat_eigvec)

    collected_orb_cube_list = []
    for i in range(n_collect):
        output_filename = 'projected_orb' + str(i)+ '.cube'
        ieigen = n_to_proj - i - 1
        cubedata = np.zeros([kabc[0],kabc[1],kabc[2]])
        for iorb in range(n_to_proj):
            cubedata += cube_orb_to_proj[iorb]*proj_mat_eigvec[iorb,ieigen]

        collected_orb_cube_list.append(cubedata)

        if lwrite:
            write_cube_file(output_filename,natoms,crdorg,kabc,abc_grid,iatsrl,crdatm,cubedata,'\n')

    return collected_orb_cube_list

